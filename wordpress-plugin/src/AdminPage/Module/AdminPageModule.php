<?php

declare(strict_types=1);

namespace Loopress\AdminPage\Module;

use Loopress\Contract\Module;
use Loopress\Infrastructure\Narrow;
use Loopress\Pushes\PushLog;
use WP_Admin_Bar;

final readonly class AdminPageModule implements Module
{
    public function __construct(private PushLog $pushLog) {}

    public function boot(): void
    {
        add_action('admin_menu', [$this, 'addMenuPage']);
        // Front end included: the admin bar shows there too for logged-in admins.
        add_action('admin_bar_menu', [$this, 'addAdminBarNode'], 100);
        // Fires on every admin screen, unlike enqueueScripts below, because the menu
        // icon it styles sits in the sidebar that's present on every admin screen.
        add_action('admin_enqueue_scripts', [$this, 'enqueueMenuIconStyle']);
        add_action('admin_enqueue_scripts', [$this, 'enqueueScripts']);
    }

    public function addMenuPage(): void
    {
        add_menu_page(
            'Loopress',
            'Loopress',
            'manage_options',
            'loopress',
            [$this, 'renderPage'],
            LOOPRESS_PLUGIN_URL . 'assets/logo.svg',
            100
        );
    }

    // The Loopress link in the top bar, with the site's Loopress state in its hover dropdown.
    public function addAdminBarNode(WP_Admin_Bar $bar): void
    {
        if (!current_user_can('manage_options')) {
            return;
        }

        $bar->add_node([
            'id'    => 'loopress',
            'title' => '<img src="' . esc_url(LOOPRESS_PLUGIN_URL . 'assets/logo.svg') . '" alt="" style="width:16px;height:16px;margin:0 6px 0 0;vertical-align:text-bottom" />Loopress',
            'href'  => admin_url('admin.php?page=loopress'),
        ]);

        $push = $this->pushLog->lastPush();
        $at   = $push === null ? false : strtotime((string) $push['at']);
        $info = [
            'version'     => 'Version: ' . LOOPRESS_VERSION,
            'environment' => 'Environment: ' . wp_get_environment_type(),
            'last-push'   => 'Last push: ' . ($push === null
                ? 'never'
                : sprintf('%s, %s ago', (string) $push['label'], human_time_diff($at === false ? time() : $at))),
        ];

        foreach ($info as $id => $text) {
            $bar->add_node(['parent' => 'loopress', 'id' => "loopress-{$id}", 'title' => esc_html($text)]);
        }
    }

    public function enqueueMenuIconStyle(): void
    {
        wp_register_style('loopress-admin-icon', false, [], LOOPRESS_VERSION);
        wp_enqueue_style('loopress-admin-icon');
        wp_add_inline_style(
            'loopress-admin-icon',
            '#toplevel_page_loopress .wp-menu-image img { width: 26px; height: 100%; padding: 0; vertical-align: middle }'
        );
    }

    public function enqueueScripts(string $hook): void
    {
        if ($hook !== 'toplevel_page_loopress') {
            return;
        }

        $assetFile = LOOPRESS_PLUGIN_PATH . 'build/index.asset.php';
        /** @var array{dependencies: list<non-empty-string>, version: string} $asset generated by wp-scripts */
        $asset     = file_exists($assetFile)
            ? require_once $assetFile
            : ['dependencies' => [], 'version' => '1.0.0'];

        wp_enqueue_script(
            'loopress-admin',
            LOOPRESS_PLUGIN_URL . 'build/index.js',
            $asset['dependencies'],
            $asset['version'],
            true
        );

        wp_enqueue_style('wp-components');
        // #wpcontent's left padding is wp-admin core chrome, not ours to edit directly;
        // this page's own layout (Page component) already handles its own spacing.
        wp_add_inline_style('wp-components', '#wpcontent { padding-left: 0; }');

        $pluginData = get_file_data(LOOPRESS_PLUGIN_PATH . 'loopress.php', ['Version' => 'Version']);

        // Extended through this filter by optional feature modules, which report their
        // own health data (the Plus edition's autoload status today) without this shared
        // code ever referencing them directly.
        $data = apply_filters('loopress_admin_data', [
            'apiUrl'        => get_rest_url(null, 'loopress/v1'),
            'nonce'         => wp_create_nonce('wp_rest'),
            'phpVersion'    => PHP_VERSION,
            'pluginVersion' => $pluginData['Version'] ?? '',
            'autoloadError' => null,
            'environment'   => wp_get_environment_type(),
            'restUrl'       => get_rest_url(),
            // The URL to give `lps project config`, shown pre-filled before the first push.
            'siteUrl'       => home_url(),
        ]);
        wp_localize_script('loopress-admin', 'loopressData', Narrow::map($data));
    }

    public function renderPage(): void
    {
        echo '<div id="loopress-admin-root"></div>';
    }
}
